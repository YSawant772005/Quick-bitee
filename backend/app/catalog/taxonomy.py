def resolve_food_types(food_type: str) -> tuple[str, ...]:
    """Return the ordered candidate list for ``food_type`` (never empty)."""
    seen: list[str] = []
    queue: Iterable[str] = (food_type,)
    for candidate in queue:
        if candidate not in seen:
            seen.append(candidate)
    for candidate in tuple(FOOD_TYPE_FALLBACKS.get(food_type, ())):
        if candidate not in seen:
            seen.append(candidate)
    if not seen:
        seen.append("indian-starters")
    return tuple(seen)


def family_for(food_type: str) -> tuple[str, ...]:
    for family, chain in FOOD_TYPE_FAMILIES.items():
        if food_type.startswith(family):
            return chain
    return ()
