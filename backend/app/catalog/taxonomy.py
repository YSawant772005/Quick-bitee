"""Global food taxonomy: categories, food types and image fallback chains.

Pure data, no I/O, no database. Both the seeder and the image pipeline import
this module so the two always agree on slugs.

Design notes
------------
* A **global category** (``kind="global"``) is a cross-restaurant browsing
  dimension such as ``pizza`` or ``beverages``. A dish may belong to several.
* A **food type** (``paneer-tikka``) is the unit used to pick a photograph.
  Every food type carries an ordered *fallback chain*: if no dedicated photo
  exists for ``paneer-tikka``, the resolver tries ``tandoori-grill`` and only
  then ``indian-starters``. This keeps images plausible instead of random.
* Diet is modelled as two global categories (``vegetarian`` / ``non-vegetarian``)
  so no extra column is needed on ``menu_items``.
"""

