"""The 120 restaurant concepts that make up the QuickBitee marketplace.

Each concept declares a *menu plan* — the sections it serves and which
:mod:`app.catalog.recipes` recipe fills each section. Two restaurants that share
a recipe still end up with different dishes because the builder hands each one a
different deterministic slice of that recipe's pool (see
:mod:`app.catalog.build`), which is what keeps 120 menus from collapsing into the
same list with different headings.

``cuisine`` is the single free-text string the existing customer app filters on
(``/explore?cuisine=…``), so it stays short and conventional.
"""

from __future__ import annotations

from dataclasses import dataclass, field


@dataclass(frozen=True)
class Section:
    """One menu section: a recipe plus the heading shown in the UI."""

    recipe: str
    title: str


@dataclass(frozen=True)
class Concept:
    key: str
    name: str
    cuisine: str
    description: str
    cover_food_type: str
    sections: tuple[Section, ...]
    #: Compared with sibling concepts so a "premium" house prices higher.
    price_tier: int = 0

    @property
    def section_count(self) -> int:
        return len(self.sections)


def _s(recipe: str, title: str) -> Section:
    return Section(recipe=recipe, title=title)


