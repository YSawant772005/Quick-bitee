#: ``(base ids, method ids)`` groups that read naturally together.
GroupSpec = tuple[tuple[str, ...], tuple[str, ...]]


@dataclass(frozen=True)
class ExplicitItem:
    name: str
    description: str
    food_type: str
    veg: bool
    price_minor: int
    tags: tuple[str, ...] = ()


@dataclass(frozen=True)
class Dish:
    name: str
    description: str
    price_minor: int
    food_type: str
    veg: bool
    tags: tuple[str, ...]


@dataclass(frozen=True)
class Recipe:
    key: str
    title: str
    tags: tuple[str, ...]
    groups: tuple[GroupSpec, ...] = ()
    explicit: tuple[ExplicitItem, ...] = ()
    price_min: int = 7900
    price_max: int = 39900

    # -- candidate construction -----------------------------------------
    def candidates(self) -> list[Dish]:
        if self.explicit:
            return [
                Dish(
                    name=item.name,
                    description=item.description,
                    price_minor=item.price_minor,
                    food_type=item.food_type,
                    veg=item.veg,
                    tags=item.tags or self.tags,
                )
                for item in self.explicit
            ]

        out: list[Dish] = []
        seen: set[str] = set()
        for base_ids, method_ids in self.groups:
            for base_id in base_ids:
                for method_id in method_ids:
                    b_label, b_veg, b_food, b_clause = _BASES[base_id]
                    m_label, m_clause, m_suffix, m_default, m_delta = _METHODS[method_id]
                    name = f"{b_label} {m_label}"
                    if name in seen:
                        continue
                    seen.add(name)

                    food = f"{b_food}-{m_suffix}" if m_suffix else b_food
                    if food not in _KNOWN_FOODS:
                        food = m_default

                    price = _price_for(name, self.price_min, self.price_max, m_delta)
                    out.append(
                        Dish(
                            name=name,
                            description=f"{b_clause} {m_clause}.",
                            price_minor=price,
                            food_type=food,
                            veg=b_veg,
                            tags=self.tags,
                        )
                    )
        return out

    def build(self, count: int, rotation: int) -> list[Dish]:
        pool = self.candidates()
        if not pool:
            raise ValueError(f"recipe {self.key!r} produced no candidates")
        if count > len(pool):
            raise ValueError(
                f"recipe {self.key!r} needs {count} dishes but only has "
                f"{len(pool)} distinct candidates"
            )
        offset = rotation % len(pool)
        rotated = pool[offset:] + pool[:offset] if offset else list(pool)
        return rotated[:count]


def _price_for(name: str, lo: int, hi: int, delta: int) -> int:
    span = max((hi - lo) // 100, 1)
    value = lo + (_h(name) % span) * 100 + delta
    return max(lo, min(hi, value))


