"""Deterministic dish generation.

Two mechanisms:

* **Combinatorial recipes** — a set of *bases* (``Paneer``, ``Chicken``…) crossed
  with *methods* (``Tikka``, ``Masala``…) restricted to groups that read
  naturally together. This yields hundreds of genuinely distinct, plausible
  dish names without hand-writing every row, and without inventing
  "Paneer 1 / Paneer 2" style duplicates.
* **Explicit pools** — used where a hand-written list reads better (beverages,
  sweets, thalis, regional specialties).

Every generated :class:`Dish` carries ``food_type`` so the image resolver can
pick a photograph that actually matches the dish, plus the global category
slugs it belongs to.

Nothing here performs I/O or touches the database.
"""

